var fs2 = __toESM(require("fs"));
var os2 = __toESM(require("os"));
var path2 = __toESM(require("path"));
var crypto2 = __toESM(require("crypto"));
var LocalSyncCache = class {
  constructor(vaultIdentifier) {
    this.entries = /* @__PURE__ */ new Map();
    this.dirty = false;
    this.saveTimer = null;
    const hash = crypto2.createHash("sha256").update(vaultIdentifier, "utf8").digest("hex").slice(0, 12);
    const cacheDir = path2.join(os2.homedir(), ".obsidian-gemini-sync");
    this.cacheFilePath = path2.join(cacheDir, `${hash}-index.json`);
    this.loadFromDisk();
  }
  getCacheFilePath() {
    return this.cacheFilePath;
  }
  loadFromDisk() {
    if (!fs2.existsSync(this.cacheFilePath))
      return;
    const raw = fs2.readFileSync(this.cacheFilePath, "utf8");
    if (!raw.trim())
      return;
    const parsed = JSON.parse(raw);
    if (parsed && parsed.version === 2 && parsed.entries && typeof parsed.entries === "object") {
      for (const [filePath, tuple] of Object.entries(parsed.entries)) {
        if (Array.isArray(tuple) && tuple.length >= 3) {
          this.entries.set(filePath, {
            path: filePath,
            driveId: String(tuple[0]),
            hash: String(tuple[1]),
            lastModified: Number(tuple[2])
          });
        }
      }
    }
  }
  /**
   * One-time seamless migration of legacy settings.syncIndex from data.json into external cache.
   * Returns true if entries were migrated so caller can slim down data.json.
   */
  migrateFromLegacySyncIndex(legacyIndex) {
    if (!legacyIndex || typeof legacyIndex !== "object")
      return false;
    const keys = Object.keys(legacyIndex);
    if (keys.length === 0)
      return false;
    for (const [filePath, entry] of Object.entries(legacyIndex)) {
      if (!entry || !entry.driveId || !entry.hash)
        continue;
      const existing = this.entries.get(filePath);
      if (!existing || (entry.lastModified || 0) >= (existing.lastModified || 0)) {
        this.entries.set(filePath, {
          path: filePath,
          driveId: entry.driveId,
          hash: entry.hash,
          lastModified: entry.lastModified || 0
        });
      }
    }
    this.dirty = true;
    this.flushSync();
    return true;
  }
  get(filePath) {
    return this.entries.get(filePath);
  }
  set(entry) {
    const prev = this.entries.get(entry.path);
    if (prev && prev.driveId === entry.driveId && prev.hash === entry.hash && prev.lastModified === entry.lastModified) {
      return;
    }
    this.entries.set(entry.path, entry);
    this.dirty = true;
  }
  delete(filePath) {
    if (this.entries.delete(filePath)) {
      this.dirty = true;
    }
  }
  clear() {
    this.entries.clear();
    this.dirty = true;
    this.flushSync();
  }
  size() {
    return this.entries.size;
  }
  scheduleFlush(delayMs = 2e3) {
    if (!this.dirty)
      return;
    if (this.saveTimer)
      clearTimeout(this.saveTimer);
    this.saveTimer = setTimeout(() => {
      this.saveTimer = null;
      this.flushSync();
    }, delayMs);
  }
  flushSync() {
    if (this.saveTimer) {
      clearTimeout(this.saveTimer);
      this.saveTimer = null;
    }
    if (!this.dirty)
      return;
    const dir = path2.dirname(this.cacheFilePath);
    fs2.mkdirSync(dir, { recursive: true });
    const compact = {};
    for (const [filePath, e] of this.entries.entries()) {
      compact[filePath] = [e.driveId, e.hash, e.lastModified];
    }
    const payload = { version: 2, entries: compact };
    const tmpPath = `${this.cacheFilePath}.tmp`;
    fs2.writeFileSync(tmpPath, JSON.stringify(payload), "utf8");
    fs2.renameSync(tmpPath, this.cacheFilePath);
    this.dirty = false;
  }
};

