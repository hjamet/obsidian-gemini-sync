function pLimit(limit) {
  const queue = [];
  let activeCount = 0;
  const next = () => {
    activeCount--;
    if (queue.length > 0) {
      const job = queue.shift();
      if (job)
        job();
    }
  };
  const run = async (fn, resolve, reject) => {
    activeCount++;
    try {
      const result = await fn();
      resolve(result);
    } catch (err) {
      reject(err);
    } finally {
      next();
    }
  };
  const enqueue = (fn) => {
    return new Promise((resolve, reject) => {
      const job = () => run(fn, resolve, reject);
      if (activeCount < limit) {
        job();
      } else {
        queue.push(job);
      }
    });
  };
  return enqueue;
}

